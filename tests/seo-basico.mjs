import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const doc = new JSDOM(readFileSync('dist/index.html','utf8')).window.document;
const titulo = 'Casal na Estrada | Viagens de moto em Pernambuco e no Nordeste';
assert.equal(doc.title,titulo);
assert.equal(doc.querySelector('meta[property="og:title"]').content,titulo);
const descricao=doc.querySelector('meta[name="description"]').content;
assert.match(descricao,/Cieri e Milla/);
assert.match(descricao,/Recife/);
assert.match(descricao,/Pernambuco e no Nordeste/);
assert.equal(doc.querySelector('meta[property="og:description"]').content,descricao);
assert.equal(doc.querySelectorAll('h1').length,1);
assert.match(doc.querySelector('h1').textContent.replace(/\s+/g,' '),/Duas pessoas,uma moto,o Brasil inteiro\./);
const capa=doc.querySelector('.hero__lead').textContent.replace(/\s+/g,' ');
for(const termo of ['Recife','mototurismo','bate-voltas','encontros de motociclistas','Pernambuco','Nordeste'])assert.ok(capa.includes(termo));
assert.ok(doc.querySelector('a[href="https://instagram.com/casal_naestrada2.4"]'));
const diario=new JSDOM(readFileSync('dist/diario/index.html','utf8')).window.document;
assert.equal(diario.title,'Diário — Casal na Estrada');
const ficha=JSON.parse(doc.querySelector('script[type="application/ld+json"]').textContent);
assert.equal(ficha.name,'Casal na Estrada');assert.equal(ficha.alternateName,'Cieri & Milla');
assert.equal(ficha.description,descricao);
console.log('SEO básico: título/descrição/OG/JSON-LD coerentes; H1, Instagram e título próprio do Diário preservados.');
