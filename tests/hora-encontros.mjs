import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import {PGlite} from '@electric-sql/pglite';
const exp={};new Function('exports',ts.transpile(readFileSync('src/lib/tempo-encontros.ts','utf8'),{module:ts.ModuleKind.CommonJS}))(exp);
const {limitesEncontro,estadoEncontro}=exp;
const dia=new Date(2026,10,21,12);
const horario=limitesEncontro(dia,undefined,'18:30');
assert.equal(horario.inicio,Date.parse('2026-11-21T18:30:00-03:00'));
assert.equal(horario.fim,Date.parse('2026-11-22T00:00:00-03:00'));
assert.equal(estadoEncontro(horario.inicio,horario.fim,horario.inicio-1),'futuro');
assert.equal(estadoEncontro(horario.inicio,horario.fim,horario.inicio),'andamento');
assert.equal(estadoEncontro(horario.inicio,horario.fim,horario.fim),'passado');
assert.equal(limitesEncontro(dia,new Date(2026,10,23,12),'23:59').fim,Date.parse('2026-11-24T00:00:00-03:00'));
for(const hora of [undefined,'','24:00','18:60','javascript:x'])assert.equal(limitesEncontro(dia,undefined,hora).inicio,Date.parse('2026-11-21T00:00:00-03:00'));
assert.equal(limitesEncontro(dia,undefined,'00:00').inicio,Date.parse('2026-11-21T00:00:00-03:00'));
const db=new PGlite();await db.exec('create table encontros(id int);insert into encontros values(1);');
const sql=readFileSync('supabase/migrations/202611210003_hora_inicio_encontros.sql','utf8');await db.exec(sql);await db.exec(sql);
assert.equal((await db.query('select hora_inicio from encontros')).rows[0].hora_inicio,null);
for(const hora of ['00:00','18:30','23:59',null])await db.query('update encontros set hora_inicio=$1',[hora]);
for(const hora of ['','24:00','1:00','12:60','18:30:00','18:30\n'])await assert.rejects(db.query('update encontros set hora_inicio=$1',[hora]));
await db.close();console.log('Horário: UTC−03, início exato, fim do último dia, legado sem hora e SQL idempotente aprovados.');
